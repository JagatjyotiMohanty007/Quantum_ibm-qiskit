# ============================================
# Classical Data Types in Python
# ============================================

def show_classical_types():
    i = 42              # int
    d = 3.14            # float
    b = True            # bool
    s = "Qiskit"        # string
    arr = [1, 2, 3]     # list
    t = (1, 2)          # tuple

    print(i, d, b, s, arr, t)

if __name__ == "__main__":
    show_classical_types()